// A fake file system: absolute path -> contents.
function reader(files: Record<string, string>) {
    return async (file: string) => files[path.resolve(file)];
}

test('collectMainIncludes: a dev file that includes requirements.txt', async () => {
    const dev = '/repo/requirements-dev.txt';
    const text = `-r requirements.txt
-r requirements-test.txt
pytest>=8
requests==2.32.3
`;
    const result = await collectMainIncludes(dev, text, reader({
        '/repo/requirements.txt': 'requests==2.32.3\nidna>=3.0\n',
        '/repo/requirements-test.txt': 'coverage\n',
    }));
    // The test file is development requirements too: it stays in the dev group.
    assert.deepEqual(result.mainIncludes, [path.resolve('/repo/requirements.txt')]);
    // requests is listed by the dev file itself, so it is not taken back out.
    assert.deepEqual(result.inheritedPackages, ['idna']);
});

test('collectMainIncludes: follows the includes of what it includes, and survives a cycle', async () => {
    const dev = '/repo/requirements/dev.txt';
    const result = await collectMainIncludes(dev, '-r base.txt\nruff\n', reader({
        '/repo/requirements/base.txt': '-r common.txt\nfastapi\n',
        '/repo/requirements/common.txt': '-r base.txt\npydantic\n',
    }));
    assert.deepEqual(result.mainIncludes, [path.resolve('/repo/requirements/base.txt')]);
    assert.deepEqual(result.inheritedPackages, ['fastapi', 'pydantic']);
});

test('collectMainIncludes: an unreadable include contributes nothing', async () => {
    const result = await collectMainIncludes('/repo/requirements-dev.txt', '-r requirements.txt\npytest\n', reader({}));
    assert.deepEqual(result.mainIncludes, [path.resolve('/repo/requirements.txt')]);
    assert.deepEqual(result.inheritedPackages, []);
});

test('collectMainIncludes: no includes, nothing to do', async () => {
    const result = await collectMainIncludes('/repo/requirements-dev.txt', 'pytest\nruff\n', reader({}));
    assert.deepEqual(result, { mainIncludes: [], inheritedPackages: [] });
});

