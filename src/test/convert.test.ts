test('displayCommand: long commands are cut short with a count', () => {
    assert.equal(displayCommand('uv add -r requirements.txt'), 'uv add -r requirements.txt');
    const names = Array.from({ length: 40 }, (_, i) => `package-${i}`);
    const shown = displayCommand(`uv remove --dev ${names.join(' ')}`);
    assert.ok(shown.startsWith('uv remove --dev package-0 package-1 '));
    assert.match(shown, / … \(\+\d+ more\)$/);
    const hidden = Number(shown.match(/\+(\d+) more/)![1]);
    const listed = shown.replace(/ … .*$/, '').split(' ').length - 3;
    assert.equal(listed + hidden, names.length);
});

// The confirmation's one job: what it lists is what the button runs.
function assertListsEveryCommand(detail: string, commands: string[]) {
    for (const command of commands) {
        assert.ok(detail.includes(displayCommand(command)), `detail should list: ${command}\n---\n${detail}`);
    }
}

test('convertPrompt: requirements.txt in a folder with no pyproject.toml', () => {
    const commands = {
        main: [INIT_COMMAND, 'uv add -r requirements.txt'],
        dev: [INIT_COMMAND, 'uv add --dev -r requirements.txt'],
    };
    const prompt = convertPrompt({
        folderName: 'my-app',
        requirementsPath: 'requirements.txt',
        choices: convertChoices('main'),
        commands,
        mainIncludes: [],
    });
    assert.equal(prompt.message, 'Convert my-app to a uv project?');
    assertListsEveryCommand(prompt.detail, commands.main);
    assert.ok(!prompt.detail.includes('--dev'), 'a single-choice prompt lists only what it runs');
    assert.match(prompt.detail, /creates pyproject\.toml and nothing else/);
    assert.match(prompt.detail, /requirements\.txt is read, not changed\./);
});

