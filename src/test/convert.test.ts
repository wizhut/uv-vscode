test('convertPrompt: a dev file lists both choices, dev first, and explains the include', () => {
    const commands = {
        main: [INIT_COMMAND, 'uv add -r requirements-dev.txt'],
        dev: [
            INIT_COMMAND,
            'uv add -r requirements.txt',
            'uv add --dev -r requirements-dev.txt',
            'uv remove --dev idna requests',
        ],
    };
    const prompt = convertPrompt({
        folderName: 'my-app',
        requirementsPath: 'requirements-dev.txt',
        choices: convertChoices('dev'),
        commands,
        mainIncludes: ['requirements.txt'],
        unsaved: true,
    });
    assert.equal(prompt.message, 'Where should the packages in requirements-dev.txt go?');
    assertListsEveryCommand(prompt.detail, commands.dev);
    assertListsEveryCommand(prompt.detail, commands.main);
    assert.ok(prompt.detail.indexOf('Dev Group runs') < prompt.detail.indexOf('Main Dependencies runs'));
    assert.match(prompt.detail, /includes requirements\.txt, so Dev Group first imports it into the project's dependencies, then takes those packages back out of the dev group\./);
    assert.match(prompt.detail, /unsaved changes to requirements-dev\.txt are saved first/);
});
